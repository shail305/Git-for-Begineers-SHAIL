
# This is a simple calculator module that provides basic arithmetic operations such as addition, subtraction, multiplication, division, and exponentiation. Each function takes two arguments and returns the result of the corresponding operation.    


def addnum( a, b):
    # This function takes two numbers as input and returns their sum.
    return a + b

def divde( a, b):
    # This function takes two numbers as input and returns the result of dividing the first number by the second number.
    return a / b

def subnum(self, a, b):
    # This function takes two numbers as input and returns the result of subtracting the second number from the first number.
    return a - b

def pow(self, a, b):
    # This function takes two numbers as input and returns the result of raising the first number to the power of the second number.
    return a ** b

def multiplynum( a, b):
    # This function takes two numbers as input and returns their product.
    return a * b
